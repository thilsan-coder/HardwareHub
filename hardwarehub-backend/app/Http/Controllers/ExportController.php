    /**
     * Export complete product catalog as a beautifully formatted Excel (.xlsx) spreadsheet.
     */
    public function exportProductsCsv(Request $request): StreamedResponse
    {
        $filename = 'HardwareHub_Products_Catalog_' . date('Y-m-d_His') . '.xlsx';

        $spreadsheet = new Spreadsheet();
        $sheet = $spreadsheet->getActiveSheet();
        $sheet->setTitle('Products Catalog');
        $sheet->setShowGridLines(true);

        $generatedAt = date('Y-m-d H:i:s');
        $generatedBy = Auth::user()?->name ?? 'System Administrator';

        $totalProducts = Product::count();
        $totalUnits = (int) Product::sum('quantity');
        $totalValuation = (float) Product::selectRaw('SUM(price * quantity) as total_val')->value('total_val');
        $lowStockCount = Product::where('quantity', '>', 0)
            ->whereColumn('quantity', '<=', 'low_stock_threshold')
            ->count();
        $outOfStockCount = Product::where('quantity', '<=', 0)->count();

        // 1. Top Brand Banner (Row 1-2)
        $sheet->mergeCells('A1:L1');
        $sheet->setCellValue('A1', 'HARDWAREHUB — MASTER PRODUCT CATALOG & INVENTORY VALUATION');
        $sheet->getRowDimension(1)->setRowHeight(36);
        $sheet->getStyle('A1')->applyFromArray([
            'font' => ['bold' => true, 'color' => ['rgb' => 'FFFFFF'], 'size' => 14, 'name' => 'Segoe UI'],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => '1E1B4B']], // Dark Indigo Navy
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER],
        ]);

        // 2. Metadata Information Strip (Row 3-4)
        $sheet->setCellValue('A3', 'Generated On:');
        $sheet->setCellValue('B3', $generatedAt);
        $sheet->setCellValue('D3', 'Generated By:');
        $sheet->setCellValue('E3', $generatedBy);
        $sheet->setCellValue('G3', 'Catalog Total Items:');
        $sheet->setCellValue('H3', $totalProducts . ' products');
        $sheet->setCellValue('J3', 'Total Stock In Hand:');
        $sheet->setCellValue('K3', number_format($totalUnits) . ' units');

        $sheet->setCellValue('A4', 'Total Valuation:');
        $sheet->setCellValue('B4', '$ ' . number_format($totalValuation, 2));
        $sheet->setCellValue('D4', 'Low Stock Alert:');
        $sheet->setCellValue('E4', $lowStockCount . ' items');
        $sheet->setCellValue('G4', 'Out of Stock:');
        $sheet->setCellValue('H4', $outOfStockCount . ' items');
        $sheet->setCellValue('J4', 'System Status:');
        $sheet->setCellValue('K4', 'ACTIVE & VERIFIED');

        $sheet->getStyle('A3:L4')->applyFromArray([
            'font' => ['size' => 10, 'name' => 'Segoe UI'],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => 'F8FAFC']],
        ]);
        $sheet->getStyle('A3')->getFont()->setBold(true);
        $sheet->getStyle('D3')->getFont()->setBold(true);
        $sheet->getStyle('G3')->getFont()->setBold(true);
        $sheet->getStyle('J3')->getFont()->setBold(true);
        $sheet->getStyle('A4')->getFont()->setBold(true);
        $sheet->getStyle('D4')->getFont()->setBold(true);
        $sheet->getStyle('G4')->getFont()->setBold(true);
        $sheet->getStyle('J4')->getFont()->setBold(true);

        // 3. Table Column Headers (Row 6)
        $headers = [
            'A6' => 'Item #',
            'B6' => 'SKU Code',
            'C6' => 'Product Name',
            'D6' => 'Category',
            'E6' => 'Unit Price ($)',
            'F6' => 'Stock In Hand',
            'G6' => 'Alert Limit',
            'H6' => 'Stock Health Status',
            'I6' => 'Total Valuation ($)',
            'J6' => 'Product Status',
            'K6' => 'Description / Specifications',
            'L6' => 'Registered Date & Time',
        ];

        foreach ($headers as $cell => $text) {
            $sheet->setCellValue($cell, $text);
        }

        $sheet->getRowDimension(6)->setRowHeight(28);
        $sheet->getStyle('A6:L6')->applyFromArray([
            'font' => ['bold' => true, 'color' => ['rgb' => 'FFFFFF'], 'size' => 10.5, 'name' => 'Segoe UI'],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => '4338CA']], // Modern Indigo
