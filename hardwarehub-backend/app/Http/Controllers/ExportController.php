        $sheet->setCellValue('A3', 'Generated On:');
        $sheet->setCellValue('B3', $generatedAt);
        $sheet->setCellValue('D3', 'Generated By:');
        $sheet->setCellValue('E3', $generatedBy);
        $sheet->setCellValue('G3', 'Critical Items to Reorder:');
        $sheet->setCellValue('H3', $totalItemsToReorder . ' products');

        $sheet->setCellValue('A4', 'Total Units Needed:');
        $sheet->setCellValue('B4', number_format($totalUnitsToOrder) . ' units');
        $sheet->setCellValue('D4', 'Est. Purchase Budget:');
        $sheet->setCellValue('E4', '$ ' . number_format($totalEstRestockCost, 2));
        $sheet->setCellValue('G4', 'Priority Level:');
        $sheet->setCellValue('H4', 'URGENT PURCHASE ACTION');

        $sheet->getStyle('A3:J4')->applyFromArray([
            'font' => ['size' => 10, 'name' => 'Segoe UI'],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => 'FEF2F2']],
        ]);
        $sheet->getStyle('A3')->getFont()->setBold(true);
        $sheet->getStyle('D3')->getFont()->setBold(true);
        $sheet->getStyle('G3')->getFont()->setBold(true);
        $sheet->getStyle('A4')->getFont()->setBold(true);
        $sheet->getStyle('D4')->getFont()->setBold(true);
        $sheet->getStyle('G4')->getFont()->setBold(true);

        // Headers
        $headers = [
            'A6' => 'Priority #',
            'B6' => 'SKU Code',
            'C6' => 'Product Name',
            'D6' => 'Category',
            'E6' => 'Current Stock',
            'F6' => 'Alert Limit',
            'G6' => 'Suggested Reorder Qty',
            'H6' => 'Unit Price ($)',
            'I6' => 'Est. Reorder Cost ($)',
